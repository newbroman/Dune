android {
    namespace = "uk.newbroman.dune"
    compileSdk = 35

    defaultConfig {
        applicationId = "uk.newbroman.dune"
        minSdk = 26
        targetSdk = 35
        versionCode = 23
        versionName = "1.21"
    }

    // Release key is NOT in git. Locally it comes from keystore.properties (next to this
    // project's root); on GitHub the workflow recreates both from repository secrets.
    val keyProps = Properties().apply {
        val f = rootProject.file("keystore.properties")
        if (f.exists()) f.inputStream().use { load(it) }
    }
    val hasKey = keyProps.getProperty("storeFile")?.let { rootProject.file(it).exists() } == true
    signingConfigs {
        if (hasKey) create("release") {
            storeFile = rootProject.file(keyProps.getProperty("storeFile"))
            storePassword = keyProps.getProperty("storePassword")
            keyAlias = keyProps.getProperty("keyAlias")
            keyPassword = keyProps.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (hasKey) signingConfig = signingConfigs.getByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
}

