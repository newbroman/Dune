#!/usr/bin/env python3
"""Builds dune2's SettingsIndex.kt (search words for each Settings section) from SettingsScreen in Ui.kt.
Run after changing Settings:  python3 tools/gen_settings_index.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'dune2/src/main/java/uk/newbroman/dune'
src = (root / 'Ui.kt').read_text()
body = src[src.index('fun SettingsScreen'):]
body = body[:body.index('\n}\n')]
# Settings drawn by their own composables: words to find them by.
EXTRA = {
    'AiSettings': 'AI key, OpenAI, OpenRouter, Gemini, Claude, model, assistant, ask, messages, calendar',
    'HubSettings': 'Hubs, left of Home, order, swipe, Groups page',
    'CoinbaseSettings': 'Coinbase key, crypto, holdings, portfolio',
    'WakeWordSettings': 'OK Computer, wake word, voice, microphone',
    'CarPicker': 'Car, Bluetooth, head unit',
}
out, sec = [], None
for line in body.splitlines():
    m = re.search(r'section\("([^"]+)"', line)
    if m: sec = m.group(1); out.append((sec, sec)); continue
    if not sec: continue
    for m in re.finditer(r'\b(?:Toggle|LinkRow|Field)\(\s*"([^"$]+)"', line): out.append((m.group(1), sec))
    # labels chosen by if/when (e.g. "✓ … is on" / "Turn on …"): every plain string on such lines
    if re.search(r'LinkRow\((if|when)|^\s*(active|onLock|else) ->', line):
        for m in re.finditer(r'"([^"$]{6,90})"', line): out.append((m.group(1).lstrip('✓ '), sec))
    for k, v in EXTRA.items():
        if re.search(r'\b' + k + r'\(', line):
            for w in v.split(', '): out.append((w, sec))
seen, rows = set(), []
for label, s in out:
    if (label, s) in seen: continue
    seen.add((label, s)); rows.append(f'    "{label}" to "{s}",')
(root / 'SettingsIndex.kt').write_text('''package uk.newbroman.dune

// Generated by tools/gen_settings_index.py from SettingsScreen – rerun it after changing Settings.
/** Settings search: each setting's name (or search words) and the section it's in. */
val SETTINGS_INDEX: List<Pair<String, String>> = listOf(
''' + '\n'.join(rows) + '\n)\n')
print(len(rows), 'entries')
